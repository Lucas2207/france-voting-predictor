/** @type {Record<string, string>} */
const LOCALES = { fr: 'fr-FR', en: 'en-GB', es: 'es-ES', ar: 'ar-u-nu-latn' };

/** Langue courante : choix mémorisé, sinon langue du navigateur, sinon français. */
let lang = (() => {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* stockage indisponible */ }
  const nav = (navigator.language || 'fr').slice(0, 2);
  return I18N[nav] ? nav : 'fr';
})();

/**
 * Traduit une clé. Les {paramètres} sont remplacés ; « clé.one » / « clé.other » selon n.
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 * @returns {string}
 */
function t(key, params = {}) {
  const dict = I18N[lang] || I18N.fr;
  let text = dict[key];
  if (params.n !== undefined) {
    const form = Number(params.n) === 1 ? '.one' : '.other';
    text = dict[key + form] ?? text;
  }
  if (text === undefined) text = I18N.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : ''));
}

/** Applique les traductions aux éléments statiques : data-i18n (texte) et data-i18n-attr (attribut aria-label). */
function applyStatic() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = t('page.title');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(/** @type {HTMLElement} */ (el).dataset.i18n || '');
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const [attr, key] = (/** @type {HTMLElement} */ (el).dataset.i18nAttr || '').split(':');
    el.setAttribute(attr, t(key));
  });
  const sel = /** @type {HTMLSelectElement | null} */ (document.getElementById('langSelect'));
  if (sel) sel.value = lang;
}

/** Change de langue, mémorise le choix et redessine la page. @param {string} code */
function setLang(code) {
  if (!I18N[code]) return;
  lang = code;
  try { localStorage.setItem('lang', code); } catch (e) { /* ignore */ }
  applyStatic();
  if (typeof onLanguageChange === 'function') onLanguageChange();
}
